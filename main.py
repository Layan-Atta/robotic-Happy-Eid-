class SSD1306(framebuf.FrameBuffer):
    def __init__(self, width, height, external_vcc):
        self.width = width
        self.height = height
        self.external_vcc = external_vcc
        self.pages = self.height // 8
        self.buffer = bytearray(self.pages * self.width)
        super().__init__(self.buffer, self.width, self.height, framebuf.MONO_VLSB)
        self.init_display()

    def init_display(self):
        for cmd in (
            0xAE, 0x20, 0x10, 0xB0, 0xC8, 0x00, 0x10, 0x40, 0x81, 0x7F,
            0xA1, 0xA6, 0xA8, self.height - 1, 0xA3, 0xD3, 0x00, 0xD5,
            0xF0, 0xD9, 0x22, 0xDA, 0x02 if self.height == 32 else 0x12,
            0xDB, 0x20, 0x8D, 0x14, 0xAF, 0x2E
        ): self.write_cmd(cmd)

    def show(self):
        self.write_list[1] = self.buffer
        self.i2c.writevto(self.addr, self.write_list)

class SSD1306_I2C(SSD1306):
    def __init__(self, width, height, i2c, addr=0x3C, external_vcc=False):
        self.i2c = i2c
        self.addr = addr
        self.temp = bytearray(2)
        self.write_list = [b"\x40", None]
        super().__init__(width, height, external_vcc)

    def write_cmd(self, cmd):
        self.temp[0] = 0x00
        self.temp[1] = cmd
        self.i2c.writeto(self.addr, self.temp)

