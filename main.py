# دالات مساعدة لتنعيم حواف وجه الروبوت (Rounded Rect)
def draw_round_rect(x, y, w, h, r):
    oled.hline(x + r, y, w - 2 * r, 1)
    oled.hline(x + r, y + h - 1, w - 2 * r, 1)
    oled.vline(x, y + r, h - 2 * r, 1)
    oled.vline(x + w - 1, y + r, h - 2 * r, 1)
    oled.pixel(x+1, y+1, 1); oled.pixel(x+2, y+1, 1); oled.pixel(x+1, y+2, 1)
    oled.pixel(x+w-2, y+1, 1); oled.pixel(x+w-3, y+1, 1); oled.pixel(x+w-2, y+2, 1)

def fill_round_rect(x, y, w, h, r):
    oled.fill_rect(x + r, y, w - 2 * r, h, 1)
    oled.fill_rect(x, y + r, w, h - 2 * r, 1)

