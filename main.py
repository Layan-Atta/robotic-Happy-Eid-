# الأنميشن الثالث: (الألعاب النارية العشوائية)
# ----------------------------------------------------
def fireworks_animation():
    for _ in range(3):
        cx = random.randint(40, 88)
        cy = random.randint(20, 44)
        for radius in range(2, 22, 4):
            oled.fill(0)
            for angle in range(0, 360, 45):
                rad = math.radians(angle)
                px = int(cx + radius * math.cos(rad))
                py = int(cy + radius * math.sin(rad))
                if 0 <= px < 128 and 0 <= py < 64:
                    oled.pixel(px, py, 1)
            oled.show()
            time.sleep(0.06)

# ----------------------------------------------------
# الأنميشن الرابع: قلب حقيقي انسيابي نابض هندسياً
# ----------------------------------------------------
def draw_perfect_heart(scale):
    cx, cy = 64, 28
    for y_offset in range(-12, 15):
        for x_offset in range(-15, 16):
            x = x_offset / (10 * scale)
            y = -y_offset / (10 * scale)
            # المعادلة الهندسية لرسم منحنى قلب مثالي ونظيف
            if (x**2 + y**2 - 1)**3 - (x**2) * (y**3) <= 0:
                oled.pixel(cx + x_offset, cy + y_offset, 1)

def heartbeat_animation():
    for _ in range(3):
        # نبضة متضخمة
        oled.fill(0)
        draw_perfect_heart(1.2)
        oled.show()
        time.sleep(0.18)
        
        # انكماش سريع
        oled.fill(0)
        draw_perfect_heart(0.9)
        oled.show()
        time.sleep(0.12)
        
        # نبضة ثانية مزدوجة
        oled.fill(0)
        draw_perfect_heart(1.2)
        oled.show()
        time.sleep(0.18)
        
        oled.fill(0)
        oled.show()
        time.sleep(0.4)

